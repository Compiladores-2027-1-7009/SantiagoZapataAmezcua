// tokens.hpp
// Aquí defino el número de cada terminal (token) del lenguaje C_1.
// Los valores son los que aparecen en la salida esperada.
// Santiago Zapata Amezcua

#ifndef TOKENS_HPP
#define TOKENS_HPP

#define FIN     0   // fin de archivo
#define LPAR    6   // (
#define RPAR    7   // )
#define COMA    8   // ,
#define PYC     9   // ;
#define ID      10  // identificador
#define IF      11  // if
#define INT     12  // int
#define WHILE   13  // while
#define ELSE    14  // else
#define FLOAT   15  // float
#define NUMERO  16  // número entero o real

#endif
